"""Generates the Claude Code play workspace (`play/`) from host-neutral sources.

Everything under `play/` is a build artifact: absolute interpreter paths are machine-specific,
and agent definitions are rendered from `mafia.agents` + `prompts/`. Never edit `play/` by hand.
"""

from __future__ import annotations

import json
import sys
from collections.abc import Iterable
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from mafia import paths
from mafia.agents import MYSTERY_AGENTS, AgentSpec, ModelTier
from mafia.harness.identity import alias_names, seat_agent_name
from mafia.harness.tools import SEAT_TOOLS
from mafia.hosts.claude_code import MCP_SERVER_NAME, MCP_TOOL_PREFIX

GENERATED_MARKER = "generated by `mafia setup`; do not edit"

MODEL_FOR_TIER: dict[ModelTier, str] = {
    ModelTier.STRONG: "opus",
    ModelTier.BALANCED: "sonnet",
    ModelTier.FAST: "haiku",
}

# The main session drives the game only through MCP tools and Agent. Built-ins that could read
# the game database or the filesystem are denied as a second layer behind the hooks.
DENIED_BUILTINS = (
    "Bash",
    "Read",
    "Write",
    "Edit",
    "Glob",
    "Grep",
    "NotebookEdit",
    "WebFetch",
    "WebSearch",
)

HOOK_EVENTS_WITH_MATCHER = ("PreToolUse", "PostToolUse")
HOOK_EVENTS_WITHOUT_MATCHER = ("UserPromptSubmit", "SubagentStart", "SubagentStop", "Stop")

SPIKE_SEATS = (1, 2)
SEAT_COUNT = 8
SPIKE_SERVER_MODULE = "mafia.hosts.claude_code.spike.server"


@dataclass(frozen=True, slots=True)
class AgentFile:
    name: str
    description: str
    tools: tuple[str, ...]  # host-neutral tool names
    model: str
    body: str
    effort: str | None = None
    max_turns: int | None = None


def render_agent(agent: AgentFile) -> str:
    lines = [
        "---",
        f"# {GENERATED_MARKER}",
        f"name: {agent.name}",
        f"description: {agent.description}",
        f"tools: {', '.join(MCP_TOOL_PREFIX + t for t in agent.tools)}",
        f"model: {agent.model}",
    ]
    if agent.effort is not None:
        lines.append(f"effort: {agent.effort}")
    lines.append("omitClaudeMd: true")
    if agent.max_turns is not None:
        lines.append(f"maxTurns: {agent.max_turns}")
    lines.append("---")
    return "\n".join(lines) + "\n\n" + agent.body.strip() + "\n"


def agent_file_from_spec(spec: AgentSpec) -> AgentFile:
    return AgentFile(
        name=spec.name,
        description=spec.description,
        tools=spec.tools,
        model=MODEL_FOR_TIER[spec.tier],
        body=spec.prompt(),
        effort=spec.effort,
        max_turns=spec.max_turns,
    )


def spike_seat_files() -> list[AgentFile]:
    spike_dir = Path(__file__).resolve().parent / "spike" / "agents"
    return [
        AgentFile(
            name=seat_agent_name(seat),
            description="M0 하네스 검증용 좌석. spike_arm 이후에만 호출한다.",
            tools=tuple(sorted(SEAT_TOOLS)),
            model=MODEL_FOR_TIER[ModelTier.FAST],
            body=(spike_dir / f"seat-{seat}.md").read_text(encoding="utf-8"),
            max_turns=12,
        )
        for seat in SPIKE_SEATS
    ]


def game_seat_files(seat_count: int = SEAT_COUNT) -> list[AgentFile]:
    body = (paths.prompts_dir() / "agents" / "seat.md").read_text(encoding="utf-8")
    return [
        AgentFile(
            name=seat_agent_name(seat),
            description=f"마피아 게임 {seat}번 좌석 플레이어. advance가 이 좌석을 깨우라고 할 때만 호출한다.",
            tools=tuple(sorted(SEAT_TOOLS)),
            model=MODEL_FOR_TIER[ModelTier.BALANCED],
            body=body,
            effort="medium",
            max_turns=10,
        )
        for seat in range(1, seat_count + 1)
    ]


def alias_seat_files() -> list[AgentFile]:
    """Anonymous seat slots for covert (night) turns. Identical to seats except the name, which
    carries no seat number: the game maps each alias to a seat in secret."""
    body = (paths.prompts_dir() / "agents" / "seat.md").read_text(encoding="utf-8")
    return [
        AgentFile(
            name=alias,
            description="마피아 게임의 익명 플레이어 슬롯. advance가 이 이름을 깨우라고 할 때만 호출한다.",
            tools=tuple(sorted(SEAT_TOOLS)),
            model=MODEL_FOR_TIER[ModelTier.BALANCED],
            body=body,
            effort="medium",
            max_turns=10,
        )
        for alias in alias_names()
    ]


def render_skill() -> str:
    body = (paths.prompts_dir() / "skill_mafia.md").read_text(encoding="utf-8")
    return (
        "---\n"
        f"# {GENERATED_MARKER}\n"
        "name: mafia\n"
        "description: 마피아 게임을 시작하거나 이어 간다 (new / watch / continue / status).\n"
        'argument-hint: "[new [mystery] [이름] | watch [mystery] | prepare [요청] | continue | status]"\n'
        "---\n\n" + body.strip() + "\n"
    )


def hook_command(python: Path) -> str:
    return f'"{python}" -m mafia.hosts.claude_code.hooks'


def settings(python: Path) -> dict[str, Any]:
    command = [{"type": "command", "command": hook_command(python), "timeout": 30}]
    hooks: dict[str, Any] = {}
    for event in HOOK_EVENTS_WITH_MATCHER:
        hooks[event] = [{"matcher": "*", "hooks": command}]
    for event in HOOK_EVENTS_WITHOUT_MATCHER:
        hooks[event] = [{"hooks": command}]
    return {
        "permissions": {"deny": list(DENIED_BUILTINS)},
        "enabledMcpjsonServers": [MCP_SERVER_NAME],
        "hooks": hooks,
    }


def mcp_config(python: Path, server_module: str, runs_dir: Path) -> dict[str, Any]:
    return {
        "mcpServers": {
            MCP_SERVER_NAME: {
                "command": str(python),
                "args": ["-m", server_module],
                "env": {"MAFIA_RUNS_DIR": str(runs_dir)},
            }
        }
    }


SPIKE_CLAUDE_MD = """\
# mafia-with-ai 하네스 검증 워크스페이스 (M0 spike)

이 폴더는 `mafia setup --spike`가 생성한 하네스 검증용 테이블입니다.
"""


def write_workspace(play_dir: Path, *, spike: bool, python: Path | None = None) -> list[Path]:
    """Render the workspace. Returns the written files. Stale generated agents are removed."""
    python = python or Path(sys.executable)
    server_module = SPIKE_SERVER_MODULE if spike else "mafia.mcp_server.server"
    agents: list[AgentFile] = [agent_file_from_spec(s) for s in MYSTERY_AGENTS]
    agents += spike_seat_files() if spike else game_seat_files() + alias_seat_files()

    agents_dir = play_dir / ".claude" / "agents"
    agents_dir.mkdir(parents=True, exist_ok=True)
    _remove_stale_agents(agents_dir, {a.name for a in agents})

    written: list[Path] = []
    claude_md = (
        SPIKE_CLAUDE_MD
        if spike
        else (paths.prompts_dir() / "driver.md").read_text(encoding="utf-8")
    )
    written.append(_write(play_dir / "CLAUDE.md", claude_md))
    skill = play_dir / ".claude" / "skills" / "mafia" / "SKILL.md"
    if spike:
        skill.unlink(missing_ok=True)
    else:
        written.append(_write(skill, render_skill()))
    written.append(
        _write_json(play_dir / ".mcp.json", mcp_config(python, server_module, paths.runs_dir()))
    )
    written.append(_write_json(play_dir / ".claude" / "settings.json", settings(python)))
    written += [_write(agents_dir / f"{a.name}.md", render_agent(a)) for a in agents]
    return written


def _remove_stale_agents(agents_dir: Path, keep: Iterable[str]) -> None:
    keep_set = set(keep)
    for path in agents_dir.glob("*.md"):
        if path.stem not in keep_set and GENERATED_MARKER in path.read_text(encoding="utf-8"):
            path.unlink()


def _write(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


def _write_json(path: Path, data: dict[str, Any]) -> Path:
    return _write(path, json.dumps(data, ensure_ascii=False, indent=2) + "\n")
